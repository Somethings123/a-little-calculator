double add(double a,double b)
{
    double c;
    c=a+b;
    return c;
}

double sub(double a,double b)
{
    double c;
    c=a-b;
    return c;
}

double mul(double a,double b)
{
    double c;
    c=a*b;
    return c;
}

double divs(double a,double b)
{
    double c;
    if(b==0)
    {
        return 0;
    }
    c=a/b;
    return c;
}
